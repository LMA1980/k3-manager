//! Cryptographic SHA-256 implementation conforming to FIPS 180-4.
//!
//! Provides deterministic zero-dependency SHA-256 hashing for CAS store deduplication,
//! manifest integrity, and staging verification (US-18, ADR-035).

#![allow(clippy::unreadable_literal, clippy::many_single_char_names)]

